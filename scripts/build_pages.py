"""Builds the footer pages (about, FAQ, policies) and the shared footer.

Edit the content in content/pages/*.html, then run:  npm run pages
Each content file starts with <!-- title: ... --> and <!-- description: ... --> lines.
The footer is written into every page between <!-- footer:start --> and <!-- footer:end -->.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / 'content' / 'pages'
PUBLIC = ROOT / 'public'

FOOTER_GROUPS = [
    ('Shop', [('Shop all', './#shop'), ('Jeans', './#jeans'),
              ('Hoodies', './#hoodies'), ('T-shirts', './#t-shirts')]),
    ('Help', [('FAQ', 'faq.html'), ('Contact', 'contact.html'), ('Shipping', 'shipping.html'),
              ('Returns and refunds', 'returns.html')]),
    ('Legal', [('Terms of service', 'terms.html'), ('Privacy policy', 'privacy.html'),
               ('Payment policy', 'payment.html'), ('Contact information', 'contact-information.html')]),
    ('CALMST8', [('About us', 'about.html'), ('help@calmst8.com', 'mailto:help@calmst8.com'),
                 ('Instagram ↗', 'https://www.instagram.com/calmst8.world/')]),
]


def footer():
    groups = '\n'.join(
        f'      <div class="foot-group">\n        <p class="label">{title}</p>\n'
        + '\n'.join(
            f'        <a href="{href}"{" target=\"_blank\" rel=\"noopener\"" if href.startswith("http") else ""}>{label}</a>'
            for label, href in items)
        + '\n      </div>'
        for title, items in FOOTER_GROUPS)
    return f'''<!-- footer:start -->
  <footer class="foot">
    <nav class="foot-links" aria-label="Footer">
{groups}
    </nav>
    <p class="foot-mark" aria-hidden="true">CALMST8</p>
    <div class="foot-row">
      <span>© <span class="year">2026</span> CALMST8</span>
      <span>Calm state. Built for everyday.</span>
      <a href="#top">Back to top ↑</a>
    </div>
  </footer>
  <script>document.querySelectorAll('.year').forEach(el => el.textContent = new Date().getFullYear());</script>
  <!-- footer:end -->'''


def faq_accordion(body):
    """Turns <h3>question</h3><p>answer</p>... into <details> items."""
    parts = re.split(r'(<h3>.*?</h3>)', body)
    out = [parts[0].strip()]
    for i in range(1, len(parts), 2):
        question = parts[i][4:-5]
        answer = parts[i + 1].strip()
        out.append(f'<details class="faq">\n  <summary>{question}</summary>\n  <div>{answer}</div>\n</details>')
    return '\n'.join(p for p in out if p)


def page(slug, title, description, body):
    return f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{description}">
  <meta name="theme-color" content="#E5E2DC">
  <title>{title} — CALMST8</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Bodoni+Moda:ital,opsz,wght@0,6..96,400;1,6..96,400&family=Hanken+Grotesk:wght@400;500&family=IBM+Plex+Mono:wght@400&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="styles.css">
</head>
<body id="top">
  <!-- Generated by scripts/build_pages.py from content/pages/{slug}.html. Edit that file, not this one. -->
  <header class="bar scrolled">
    <nav class="bar-nav" aria-label="Main">
      <a href="./#shop">Shop</a>
      <a href="faq.html">FAQ</a>
      <a href="contact.html">Contact</a>
    </nav>
    <a class="bar-mark" href="./">CALMST8</a>
    <a class="bar-cta" href="./#shop">Shop <span aria-hidden="true">→</span></a>
  </header>

  <main class="doc doc-{slug}">
    <p class="label">CALMST8</p>
    <h1>{title}</h1>
    <div class="doc-body">
{body}
    </div>
  </main>

  {footer()}
  <script src="vendor/lenis.min.js" defer></script>
  <script src="motion.js" defer></script>
</body>
</html>
'''


def main():
    built = []
    for src in sorted(CONTENT.glob('*.html')):
        text = src.read_text()
        title = re.search(r'<!-- title: (.*?) -->', text).group(1)
        description = re.search(r'<!-- description: (.*?) -->', text).group(1)
        body = re.sub(r'<!--.*?-->\n?', '', text).strip()
        if src.stem == 'faq':
            body = faq_accordion(body)
        (PUBLIC / f'{src.stem}.html').write_text(page(src.stem, title, description, body))
        built.append(src.stem)

    # Shared footer on the home and thank-you pages
    for name in ('index.html', 'success.html'):
        path = PUBLIC / name
        html = path.read_text()
        if '<!-- footer:start -->' in html:
            html = re.sub(r'<!-- footer:start -->.*?<!-- footer:end -->', lambda _: footer(), html, flags=re.S)
        else:
            html = re.sub(r'  <footer class="foot">.*?</footer>', lambda _: '  ' + footer(), html, flags=re.S)
            if '<!-- footer:start -->' not in html:
                html = html.replace('\n  <script>', '\n  ' + footer() + '\n\n  <script>', 1)
        path.write_text(html)
    print('Built', ', '.join(built))


if __name__ == '__main__':
    main()
